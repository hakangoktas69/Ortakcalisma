import { expect, test } from '@playwright/test';
import { girisYap, ekranDenetle, hataTopla } from '../e2e/yardim.ts';
test.beforeEach(async ({ page }) => {
 const parola = process.env['DEMO_SIFRE']; if (!parola) throw new Error('Demo şifresi gerekli');
 await girisYap(page, { eposta: 'demo@eworks.test', parola });
});
test('demo onayı ve kullanım izni geri alınır, firma belgeleri korunarak arşivlenir ve geri getirilir', async ({ page, context }, info) => {
 const errors = hataTopla(page); const requests: string[] = [];
 await context.route('**/*', route => { const r = route.request(); const u = new URL(r.url()); if (['http:', 'https:'].includes(u.protocol) && (!['web', 'localhost', '127.0.0.1'].includes(u.hostname) || (u.pathname.startsWith('/api/') && r.method() !== 'GET'))) { requests.push(r.method() + ' ' + u.origin + u.pathname); return route.abort(); } return route.continue(); });
 await page.goto('/firmalar/liste');
 await page.getByRole('button', { name: /Düzenle · Demo Atlas.*mükellef bilgilerini düzenle/ }).click();
 const editor = page.getByRole('region', { name: 'Mükellef bilgileri formu' }); const controls = editor.getByRole('region', { name: 'Demo izin ve arşiv işlemleri' });
 await expect(controls.getByRole('button', { name: 'Kullanım izni ver', exact: true })).toBeDisabled();
 const consent = async () => { await controls.getByRole('button', { name: 'Mükellef onayı', exact: true }).click(); await expect(controls.getByRole('button', { name: 'Onay senaryosunu uygula' })).toBeDisabled(); await controls.getByRole('checkbox', { name: 'Örnek mükellef onayını canlandır' }).check(); await controls.getByRole('button', { name: 'Onay senaryosunu uygula' }).click(); };
 await consent(); await controls.getByRole('button', { name: 'Kullanım izni ver', exact: true }).click();
 await expect(controls.locator('dd').nth(2)).toHaveText('Verildi');
 await controls.getByRole('button', { name: 'Onayı geri al', exact: true }).click();
 await expect(controls.locator('dd').nth(1)).toHaveText('Alınmadı'); await expect(controls.locator('dd').nth(2)).toHaveText('Verilmedi');
 await consent(); await controls.getByRole('button', { name: 'Kullanım izni ver', exact: true }).click();
 await ekranDenetle(page); await controls.screenshot({ path: info.outputPath('demo-izinler.png') });
 await editor.getByRole('combobox', { name: 'Levha arşivi dönemi' }).selectOption('2026-08');
 await controls.getByRole('button', { name: 'Arşivle', exact: true }).click();
 await expect(controls.locator('dd').nth(0)).toHaveText('Arşivde'); await expect(controls.locator('dd').nth(2)).toHaveText('Verilmedi');
 await expect(editor.getByRole('button', { name: 'Aç · Vergi levhası 2026-08 örnek belge' })).toBeVisible();
 await page.getByRole('button', { name: 'Firma formunu kapat' }).click();
 await expect(page.locator('.pf-row')).toHaveCount(2);
 await page.getByRole('combobox', { name: 'Firma durumu', exact: true }).selectOption('Arşivde');
 await expect(page.locator('.pf-row')).toHaveCount(1); await expect(page.locator('.pf-row')).toContainText('Demo Atlas');
 await page.getByRole('button', { name: /mükellef bilgilerini düzenle/ }).click();
 await expect(editor.getByRole('button', { name: 'Aç · Vergi levhası 2026-08 örnek belge' })).toBeVisible();
 await controls.getByRole('button', { name: 'Arşivden çıkar', exact: true }).click();
 await expect(controls.locator('dd').nth(0)).toHaveText('Aktif listede'); await expect(controls.locator('dd').nth(2)).toHaveText('Verilmedi');
 await page.getByRole('button', { name: 'Firma formunu kapat' }).click();
 await page.getByRole('combobox', { name: 'Firma durumu', exact: true }).selectOption('');
 await expect(page.locator('.pf-row')).toHaveCount(3); await ekranDenetle(page);
 expect(requests).toEqual([]); expect(errors).toEqual([]);
});
test('örnek takvim kaynağı yinelenmeden yenilenir, kişisel not ve durumu korunur', async ({ page, context }) => {
 const errors = hataTopla(page); const requests: string[] = [];
 await context.route('**/*', route => { const r = route.request(); const u = new URL(r.url()); if (['http:', 'https:'].includes(u.protocol) && (!['web', 'localhost', '127.0.0.1'].includes(u.hostname) || (u.pathname.startsWith('/api/') && r.method() !== 'GET'))) { requests.push(r.method() + ' ' + u.origin + u.pathname); return route.abort(); } return route.continue(); });
 await page.goto('/genel_bakis/takvim');
 await page.getByRole('button', { name: 'Hatırlatma Ekle', exact: true }).click();
 const dialog = page.getByRole('dialog');
 await dialog.getByRole('textbox', { name: 'Hatırlatma başlığı' }).fill('Demo yenilemede korunacak');
 await dialog.getByRole('combobox', { name: 'İlgili mükellef' }).selectOption('atlas');
 await dialog.getByRole('button', { name: 'Örnek hatırlatmayı ekle' }).click();
 await page.getByRole('searchbox', { name: 'Takvimde ara' }).fill('yenilemede korunacak');
 const selected = page.getByRole('region', { name: 'Seçilen gün' });
 await selected.getByRole('button', { name: /yenilemede korunacak/ }).click();
 await dialog.getByRole('button', { name: 'Tamamlandı', exact: true }).click();
 await dialog.getByRole('button', { name: 'Takvim detayını kapat' }).click();
 for (let i = 0; i < 2; i++) await page.getByRole('button', { name: 'Takvimi kaynaklardan güncelle', exact: true }).click();
 await expect(selected.getByRole('button', { name: /yenilemede korunacak/ })).toHaveCount(1);
 await selected.getByRole('button', { name: /yenilemede korunacak/ }).click();
 await expect(dialog.getByText('Tamamlandı', { exact: true })).toHaveCount(2);
 await expect(dialog).toContainText('Demo Atlas'); await dialog.getByRole('button', { name: 'Takvim detayını kapat' }).click();
 await expect(page.getByRole('status').filter({ hasText: 'Örnek kaynak takvimi yenilendi' })).toBeVisible();
 await ekranDenetle(page); expect(requests).toEqual([]); expect(errors).toEqual([]);
});
