test('ayrıntılı firma kartı, kurum durumları ve dönemli levha önizlemesi', async ({ page }, info) => {
  const errors = hataTopla(page); const writes: string[] = [];
  page.on('request', r => { if (r.url().includes('/api/') && r.method() !== 'GET') writes.push(r.url()); });
  await page.goto('/firmalar/liste');
  const firms = page.getByRole('region', { name: 'Ayrıntılı mükellef yönetimi' });
  await firms.getByRole('searchbox', { name: 'Unvan, maskeli kimlik veya NACE ara' }).fill('İNŞAAT');
  await expect(firms.locator('.pf-row')).toHaveCount(1);
  await firms.getByRole('button', { name: /mükellef bilgilerini düzenle/ }).click();
  const editor = firms.getByRole('region', { name: 'Mükellef bilgileri formu' });
  await expect(editor.getByRole('heading', { name: 'GİB Bilgileri', exact: true })).toBeVisible();
  await expect(editor.getByRole('heading', { name: 'UETS Bilgileri', exact: true })).toBeVisible();
  await page.locator('.pf-drawer').evaluate(el => { el.scrollTop = 0; });
  await page.screenshot({ path: info.outputPath('firma-formu-ust.png'), fullPage: false });
  await editor.getByRole('textbox', { name: 'Faaliyet adı', exact: true }).fill('Demo inşaat faaliyeti');
  await editor.getByRole('button', { name: 'Firma değişikliklerini uygula' }).click();
  await expect(firms).toContainText('Firma bilgileri bu ekranda güncellendi');
  await editor.getByRole('combobox', { name: 'Levha arşivi dönemi' }).selectOption('2026-08');
  const popupEvent = page.waitForEvent('popup');
  await editor.getByRole('button', { name: 'Aç · Vergi levhası 2026-08 örnek belge' }).click();
  const popup = await popupEvent; await expect(popup.getByRole('heading', { name: 'Vergi levhası', exact: true })).toBeVisible(); await expect(popup.getByRole('region', { name: 'Örnek belge önizlemesi' })).toContainText('2026-08'); await popup.close();
  const downloadEvent = page.waitForEvent('download');
  await editor.getByRole('button', { name: 'İndir · Vergi levhası 2026-08 örnek belge' }).click();
  expect((await downloadEvent).suggestedFilename()).toContain('2026-08');
  await ekranDenetle(page); await page.screenshot({ path: info.outputPath('firmalar-ayrinti.png'), fullPage: false });
  await page.getByRole('button', { name: 'Firma formunu kapat' }).click();
  await firms.getByRole('button', { name: /Yeni Firma Ekle/ }).click();
  await editor.getByRole('textbox', { name: 'Unvan', exact: true }).fill('Demo Deneme Firma');
  await editor.getByRole('button', { name: 'Firma değişikliklerini uygula' }).click();
  await page.getByRole('button', { name: 'Firma formunu kapat' }).click();
  await firms.getByRole('searchbox', { name: 'Unvan, maskeli kimlik veya NACE ara' }).fill('');
  await expect(firms.locator('.pf-row')).toHaveCount(4);
  await expect(firms.getByRole('button', { name: 'Vergi levhası · Demo Deneme Firma' })).toBeDisabled();
  expect(writes).toEqual([]); expect(errors).toEqual([]);
});

